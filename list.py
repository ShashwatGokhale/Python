
#FOR LOOP:-   For loops is used to iterate over a sequence such as a list, tuple, string or range. It executes a block of code once for each item in the sequence.
# for loop throgh list
list=["apple", "banana", "orange"]
for i in list:
     print(i)

#loop through index no.
list= ["apple", "banana", "orange"]
for i in range(len(list)):
     print(list[i])

